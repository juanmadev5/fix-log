CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text NOT NULL,
    password_hash text NOT NULL
);
CREATE UNIQUE INDEX ix_users_email ON users (email);

CREATE TABLE customers (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name         text NOT NULL,
    email        text NOT NULL,
    phone_number text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_customers_user_id ON customers (user_id);

CREATE TABLE expenses (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title      text NOT NULL,
    details    text NOT NULL,
    price      real NOT NULL CHECK (price > 0),
    quantity   integer NOT NULL CHECK (quantity > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_expenses_user_id ON expenses (user_id);

CREATE TABLE reports (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    customer_id  integer NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    date         timestamptz NOT NULL,
    details      text NOT NULL,
    is_completed boolean NOT NULL,
    is_paid      boolean NOT NULL,
    cost         numeric NOT NULL CHECK (cost >= 0),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_reports_customer_id ON reports (customer_id);
CREATE INDEX ix_reports_user_id ON reports (user_id);
